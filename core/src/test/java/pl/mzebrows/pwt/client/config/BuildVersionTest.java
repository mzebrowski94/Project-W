package pl.mzebrows.pwt.client.config;

import static org.assertj.core.api.Assertions.assertThat;

import org.junit.jupiter.api.Test;

/** The build version is what the build stamped; a copy nobody stamped still has a name. */
class BuildVersionTest {

    @Test
    void readsTheVersionTheBuildStamped() {
        String stamp = "# Generated by :lwjgl3:generateBuildVersion - do not edit.\nbuild.version=2026.11.13-b412b68\n";

        assertThat(BuildVersion.parse(stamp)).isEqualTo("2026.11.13-b412b68");
    }

    @Test
    void keepsTheMarkOfAnUncommittedTree() {
        assertThat(BuildVersion.parse("build.version=2026.11.13-b412b68-dirty\n"))
                .isEqualTo("2026.11.13-b412b68-dirty");
    }

    @Test
    void callsACopyNobodyStampedDev() {
        assertThat(BuildVersion.parse("")).isEqualTo("dev");
        assertThat(BuildVersion.parse("build.version=\n")).isEqualTo("dev");
    }

    /** The tests run without the launcher's resources, as a copy started from an IDE may. */
    @Test
    void namesThisCopyEvenWithoutAStamp() {
        assertThat(BuildVersion.current()).isNotBlank();
    }
}
