    private PixelFont() {}

    /** The font as a glyph table, for {@link GlyphFont} to build. */
    public static GlyphTable table() {
        return new GlyphTable(SIZE, BASELINE, UiFont.ADVANCE, GLYPHS);
    }

    private static void glyph(char c, String rows) {
        String packed = rows.replace("|", "");
        if (packed.length() != GLYPH_WIDTH * SIZE) {
            throw new IllegalStateException("glyph '" + c + "' is not " + GLYPH_WIDTH + " x " + SIZE);
        }
        int[] masks = new int[SIZE];
        for (int row = 0; row < SIZE; row++) {
            for (int column = 0; column < GLYPH_WIDTH; column++) {
                if (packed.charAt(row * GLYPH_WIDTH + column) == '#') {
                    masks[row] |= 1 << column;
                }
            }
        }
        GLYPHS.put(c, masks);
    }
