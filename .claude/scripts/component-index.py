#!/usr/bin/env python3
"""Regenerate docs/components.md from source. Run from the repository root."""

import pathlib, re

SIM = pathlib.Path("sim/src/main/java/pl/mzebrows/pwt/sim")
CORE = pathlib.Path("core/src/main/java/pl/mzebrows/pwt/client")


def summary(path):
    """First sentence of the first javadoc block."""
    m = re.search(r"/\*\*(.*?)\*/", path.read_text(encoding="utf-8"), re.S)
    if not m:
        return ""
    body = " ".join(re.sub(r"^\s*\*\s?", "", m.group(1).split("<p>")[0], flags=re.M).split())
    first = re.split(r"(?<=\.)\s+", body)[0].strip()
    if first.startswith("Marker:"):
        first = "Marker: " + first[len("Marker:"):].strip().capitalize()
    return first


def strip_comments(src):
    return re.sub(r"//.*", "", re.sub(r"/\*.*?\*/", "", src, flags=re.S))


def main():
    comps = sorted(p.stem for p in (SIM / "component").glob("*.java") if p.stem != "package-info")
    buckets = {
        "system": sorted((SIM / "system").glob("*.java")),
        "collision": sorted((SIM / "collision").glob("*.java")),
        "sim": sorted(p for p in SIM.glob("*.java") if p.stem != "package-info"),
        "client": sorted(CORE.glob("*.java")),
    }
    bodies = {
        k: [(p.stem, strip_comments(p.read_text(encoding="utf-8"))) for p in v] for k, v in buckets.items()
    }

    rows = []
    for c in comps:
        pat = re.compile(rf"\b{c}\b")
        hits = {k: [n for n, src in v if pat.search(src)] for k, v in bodies.items()}
        rows.append((c, summary(SIM / "component" / f"{c}.java"), hits))

    def fmt(h):
        parts = []
        if h["system"]:
            parts.append(", ".join("`%s`" % s.replace("System", "") for s in h["system"]))
        if h["collision"]:
            parts.append("solver: " + ", ".join("`%s`" % n for n in h["collision"]))
        if h["sim"]:
            parts.append(", ".join("`%s`" % n for n in h["sim"]))
        if h["client"]:
            parts.append("client: " + ", ".join("`%s`" % n for n in h["client"]))
        return " · ".join(parts) or "**nothing**"

    out = [
        """# Components

Every component in `sim`, what it holds, and what touches it. **Generated by
`.claude/scripts/component-index.py`** - regenerate rather than editing by hand, and treat a
disagreement with the code as this file being stale.

`Touched by` lists systems with the `System` suffix trimmed, then the constraint solver, then classes
in `sim` itself, then the client. A name appearing here means that class mentions the type at all - it
does not distinguish a read from a write.

**On the one-writer rule.** G0010 says a unit's state is written by exactly one system. This table
cannot prove that, only narrow where to look: a component touched by one system trivially satisfies it,
and a component touched by many is where to check. Read the code before concluding either way.
""",
        "| Component | What it holds | Touched by |",
        "|---|---|---|",
    ]
    out += [f"| **{c}** | {s} | {fmt(h)} |" for c, s, h in rows]

    lonely = [c for c, _, h in rows if len(h["system"]) == 1]
    none = [c for c, _, h in rows if not h["system"]]
    out += [
        "",
        "## Before adding a component",
        "",
        f"{len(rows)} exist. Look for one that already holds what you need: most new mechanics want a field"
        " on an existing component, not a new component - G0010 makes that structural, because only"
        " `Spawner` may change what an entity is made of, so state cannot be a component that gets added"
        " and removed.",
        "",
        "**Touched by exactly one system:** " + ", ".join(f"`{c}`" for c in lonely) + ".",
        "These satisfy the one-writer rule by construction. A second system writing one is the change worth"
        " thinking twice about.",
        "",
        "**Touched by no system:** " + ", ".join(f"`{c}`" for c in none) + ".",
        "Not dead code - markers read outside the system loop, by the client or by `Spawner` as it builds an"
        " entity. The `Touched by` column says which.",
        "",
    ]
    pathlib.Path("docs/components.md").write_text("\n".join(out), encoding="utf-8")
    print(f"docs/components.md: {len(rows)} components")


main()
