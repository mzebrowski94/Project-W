#!/usr/bin/env python3
"""Regenerate docs/components.md from source. Run from the repository root.

Every column is regenerated except *Written by*, which is the declaration ADR 0019 checks against the
bytecode: it is read back from the file as it stands and kept. A new component gets an empty cell, and
ArchitectureTest.everyComponentIsWrittenByExactlyItsDeclaredWriters says what to put in it."""

import pathlib, re

SIM = pathlib.Path("sim/src/main/java/pl/mzebrows/pwt/sim")
CORE = pathlib.Path("core/src/main/java/pl/mzebrows/pwt/client")
DOC = pathlib.Path("docs/components.md")


def summary(path):
    """First sentence of the first javadoc block."""
    m = re.search(r"/\*\*(.*?)\*/", path.read_text(encoding="utf-8"), re.S)
    if not m:
        return ""
    body = " ".join(re.sub(r"^\s*\*\s?", "", m.group(1).split("<p>")[0], flags=re.M).split())
    first = re.split(r"(?<=\.)\s+", body)[0].strip()
    if first.startswith("Marker:"):
        first = "Marker: " + first[len("Marker:"):].strip().capitalize()
    return first


def declared_writers():
    """Each component's Written by cell, as the file has it now."""
    if not DOC.exists():
        return {}
    column, cells = None, {}
    for line in DOC.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        parts = [p.strip() for p in line.split("|")]
        if "Written by" in parts:
            column = parts.index("Written by")
            continue
        m = re.fullmatch(r"\*\*(\w+)\*\*", parts[1])
        if column is not None and m:
            cells[m.group(1)] = parts[column]
    return cells


def strip_comments(src):
    return re.sub(r"//.*", "", re.sub(r"/\*.*?\*/", "", src, flags=re.S))


def main():
    comps = sorted(p.stem for p in (SIM / "component").glob("*.java") if p.stem != "package-info")
    # By name as a string: a Windows path compares case-insensitively and a Linux one does not, and the
    # index must come out the same wherever it is run.
    def by_name(paths):
        return sorted(paths, key=lambda p: p.name)

    # Recursively: every system lives in a fenced package under system/ (ADR 0020), and one moved or added
    # must not drop out of the index without anybody noticing.
    systems = [p for p in (SIM / "system").rglob("*.java") if p.stem != "package-info"]
    buckets = {
        "system": by_name(systems),
        "collision": by_name((SIM / "collision").glob("*.java")),
        "sim": by_name(p for p in SIM.glob("*.java") if p.stem != "package-info"),
        "client": by_name(CORE.rglob("*.java")),
    }
    bodies = {
        k: [(p.stem, strip_comments(p.read_text(encoding="utf-8"))) for p in v] for k, v in buckets.items()
    }

    written = declared_writers()
    rows = []
    for c in comps:
        pat = re.compile(rf"\b{c}\b")
        hits = {k: [n for n, src in v if pat.search(src)] for k, v in bodies.items()}
        rows.append((c, summary(SIM / "component" / f"{c}.java"), hits))

    def fmt(h):
        parts = []
        if h["system"]:
            parts.append(", ".join("`%s`" % s.replace("System", "") for s in h["system"]))
        if h["collision"]:
            parts.append("solver: " + ", ".join("`%s`" % n for n in h["collision"]))
        if h["sim"]:
            parts.append(", ".join("`%s`" % n for n in h["sim"]))
        if h["client"]:
            parts.append("client: " + ", ".join("`%s`" % n for n in h["client"]))
        return " · ".join(parts) or "**nothing**"

    out = [
        """# Components

Every component in `sim`, what it holds, who writes it and what touches it. **Generated by
`.claude/scripts/component-index.py`** - regenerate rather than editing by hand, and treat a
disagreement with the code as this file being stale.

`Written by` is the one column written by hand, and the build checks it (ADR 0019):
`ArchitectureTest.everyComponentIsWrittenByExactlyItsDeclaredWriters` measures who writes each component
from the bytecode and fails on any difference, either way. A write is a field set from outside the
component, a call to a method that changes it, or a change to a collection it holds; it is credited to
the system whose code reaches it, through any helper. A class that is not a system - `Simulation`,
`Picks` - is named when it writes on its own. Building a world is not a write: `Spawner`'s `spawn`
methods, a scenario laying out its level, `WorldCodec`. `-` is a component nothing writes after it is
built. The script keeps the column; when the test fails, its message is the cell to put here.

`Touched by` lists systems with the `System` suffix trimmed, then the constraint solver, then classes
in `sim` itself, then the client. A name appearing here means that class mentions the type at all - it
does not distinguish a read from a write.

**On the one-writer rule.** G0010 says a unit's state is written by exactly one system. `Written by` says
who does; whether more than one may is still G0010's question, answered by reading the code.
""",
        "| Component | What it holds | Written by | Touched by |",
        "|---|---|---|---|",
    ]
    out += [f"| **{c}** | {s} | {written.get(c, '')} | {fmt(h)} |" for c, s, h in rows]

    lonely = [c for c, _, _ in rows if written.get(c, "").count("`") == 2]
    none = [c for c, _, h in rows if not h["system"]]
    out += [
        "",
        "## Before adding a component",
        "",
        f"{len(rows)} exist. Look for one that already holds what you need: most new mechanics want a field"
        " on an existing component, not a new component - G0010 makes that structural, because only"
        " `Spawner` may change what an entity is made of, so state cannot be a component that gets added"
        " and removed.",
        "",
        "**Written by exactly one class:** " + ", ".join(f"`{c}`" for c in lonely) + ".",
        "These satisfy the one-writer rule. A second writer of one is the change worth thinking twice about.",
        "",
        "**Touched by no system:** " + ", ".join(f"`{c}`" for c in none) + ".",
        "Not dead code - markers read outside the system loop, by the client or by `Spawner` as it builds an"
        " entity. The `Touched by` column says which.",
        "",
    ]
    DOC.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"docs/components.md: {len(rows)} components")


main()
